// Writes the QartaCheckout ABI from the Foundry build output into packages/shared, as a
// TypeScript `as const` export so viem can type every call. Run after `forge build`:
//   pnpm --filter contracts export-abi
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const artifact = JSON.parse(
  readFileSync(join(root, 'out/QartaCheckout.sol/QartaCheckout.json'), 'utf8'),
);
const target = join(root, '../packages/shared/src/abi/qartaCheckout.ts');
const body =
  '// Generated by contracts/script/export-abi.mjs from the Foundry build. Do not edit by hand.\n' +
  `export const qartaCheckoutAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
writeFileSync(target, body);
console.log(`wrote ${target} (${artifact.abi.length} entries)`);
